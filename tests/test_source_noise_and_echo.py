def _codex_events(tmp_path: Path, payloads: list[dict], **kw):
    root = tmp_path / "sessions"
    rows = [{"timestamp": "2026-05-01T09:00:00Z", "type": "session_meta", "payload": {"id": "sess-x", "cwd": "/tmp/demo"}}]
    rows += [_x(i + 1, p, "event_msg" if str(p.get("type", "")).endswith(("_begin", "_end")) else "response_item")
             for i, p in enumerate(payloads)]
    _write(root / "2026" / "05" / "01" / "rollout-2026-05-01T09-00-00-aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee.jsonl", rows)
    src = CodexCliSource(sessions_root=root, history_path=tmp_path / "none.jsonl", **kw)
    return list(src.read(src.discover()[0], EPOCH, FAR))


