@pytest.mark.parametrize("text", NOISE)
def test_noise_predicate_drops_wrappers(text) -> None:
    assert is_noise_part(text)
    assert clean_message_part(text) == ""


def test_noise_predicate_keeps_real_text_and_codex_prefixes_still_work() -> None:
    assert not is_noise_part("please review the billing migration")
    assert not is_noise_part("Caveat emptor is a latin phrase")  # no colon
    assert is_noise_part("<environment_context>\n<cwd>/x</cwd>\n</environment_context>")
    assert is_noise_part("# AGENTS.md instructions for /x\n...")


def test_claude_code_filters_wrappers_keeps_conversation(tmp_path) -> None:
    rows = [_c("user", i, _text(t)) for i, t in enumerate(NOISE)]
    rows += [
        _c("user", 20, "<command-name>/clear</command-name>"),                  # content as a plain string
        _c("user", 21, _text("real question about pelican rollout")),
        _c("assistant", 22, _text("real answer about the pelican rollout")),
        _c("user", 23, [{"type": "text", "text": "<system-reminder>x</system-reminder>"},
                        {"type": "text", "text": "second real question"}]),
        _c("user", 24, _text("tail question <system-reminder>glued reminder</system-reminder>")),
    ]
    events = _claude_events(tmp_path, rows)
    assert [e.intent for e in events] == [
        "real question about pelican rollout",
        "real answer about the pelican rollout",
        "second real question",
        "tail question",
    ]
    assert [e.actor for e in events] == ["user", "assistant", "user", "user"]


# ── F6: via_penpal, Claude Code ────────────────────────────────────────────────────────────
def _echo_rows() -> list[dict]:
    return [
        _c("user", 1, _text("what did I plan for pelican")),
        _c("assistant", 2, _text("let me check my history")),
        _c("assistant", 3, _tool_use("mcp__keypulse__search_context")),
        _c("user", 4, _tool_result()),
        _c("assistant", 5, _text("Your history shows the pelican plan")),       # echo
        _c("assistant", 6, _tool_use("Bash")),
        _c("assistant", 7, _text("and a second paragraph, still a restatement")),  # echo (until next user msg)
        _c("user", 8, _text("thanks, now fix the bug")),
        _c("assistant", 9, _text("fixing the bug now")),                          # not an echo
        _c("assistant", 10, _tool_use("mcp__other__search_context")),
        _c("assistant", 11, _text("answer after a foreign MCP tool")),            # not an echo
    ]


def _marks(events) -> dict[str, bool]:
    return {e.intent: bool(e.metadata.get("via_penpal")) for e in events}


def test_claude_code_marks_assistant_text_after_keypulse_tool(tmp_path) -> None:
    marks = _marks(_claude_events(tmp_path, _echo_rows()))
    assert marks == {
        "what did I plan for pelican": False,
        "let me check my history": False,
        "Your history shows the pelican plan": True,
        "and a second paragraph, still a restatement": True,
        "thanks, now fix the bug": False,
        "fixing the bug now": False,
        "answer after a foreign MCP tool": False,
    }


