def test_search_and_timeline_exclude_echoes_by_default(db) -> None:
    keep = _ins("pelican plan from the user", "2026-05-01T10:00:00+00:00")
    echo = _ins("pelican plan restated by the assistant", "2026-05-01T10:01:00+00:00", echo=True)
    legacy_echo = _ins("pelican plan restated before the rename", "2026-05-01T10:02:00+00:00", legacy_echo=True)
    token = auth.create_grant("host", buckets=["Work"])
    from mcp_helpers import client_of

    def ids(resp):
        return {r["id"] for r in resp["results"]}

    s = tools.search_context(token, ["pelican"], client=client_of(token))
    assert ids(s) == {f"evt_{keep}"}
    s = tools.search_context(token, ["pelican"], None, None, 10, True, client=client_of(token))
    assert ids(s) == {f"evt_{keep}", f"evt_{echo}", f"evt_{legacy_echo}"}
    kw = dict(client=client_of(token))
    t = tools.get_timeline(token, "2026-05-01", "2026-05-01", **kw)
    assert ids(t) == {f"evt_{keep}"}
    t = tools.get_timeline(token, "2026-05-01", "2026-05-01", None, 50, None, True, **kw)
    assert ids(t) == {f"evt_{keep}", f"evt_{echo}", f"evt_{legacy_echo}"}
    bad = tools.search_context(token, ["pelican"], None, None, 10, "yes", client=client_of(token))
    assert bad["status"] == "invalid_argument"


def test_engine_level_flag_and_rows_with_non_json_metadata(db) -> None:
    rid = _ins("pelican plain", "2026-05-01T10:00:00+00:00")
    get_conn().execute("UPDATE raw_events SET metadata_json = 'not json' WHERE id = ?", (rid,))
    get_conn().commit()
    assert [h["id"] for h in search_events(["pelican"], buckets=["Work"])] == [rid]
    rows, _ = timeline_events(since="2026-05-01", until="2026-05-02", sources=None, buckets=["Work"])
    assert [r["id"] for r in rows] == [rid]


def test_semantic_weight_breaks_score_ties_before_recency(db) -> None:
    # identical text -> identical coverage and score; the heavier source wins even though it is older
    heavy_old = _ins("pelican rollout checklist", "2026-05-01T09:00:00+00:00", source="git_log", weight=0.9)
    light_new = _ins("pelican rollout checklist", "2026-05-02T09:00:00+00:00", source="zsh_history", weight=0.5)
    ids = [h["id"] for h in search_events(["pelican"], buckets=["Work"])]
    assert ids == [heavy_old, light_new]


def test_coverage_and_score_still_outrank_weight(db) -> None:
    two_kw = _ins("pelican rollout", "2026-05-01T09:00:00+00:00", weight=0.1)
    one_kw = _ins("pelican only", "2026-05-02T09:00:00+00:00", weight=1.0)
    ids = [h["id"] for h in search_events(["pelican", "rollout"], buckets=["Work"])]
    assert ids == [two_kw, one_kw]


# ── query-time second redaction pass (fail closed) ───────────────────────────────────────────
LEGACY_SECRET = "sk-test-FAKE0000000000000000000000"


def _legacy_row(db_text: str) -> tuple[str, str, int]:
    """A row stored before current rules existed: secret sits in content_text unredacted."""
    rid = _ins(db_text, "2026-05-01T10:00:00+00:00")
    get_conn().execute("UPDATE raw_events SET content_text = ? WHERE id = ?", (db_text, rid))
    get_conn().commit()
    token = auth.create_grant("host", buckets=["Work"])
    return token, "host", rid


def test_query_time_redaction_covers_search_timeline_evidence(db) -> None:
    from mcp_helpers import client_of
    token, _, _ = _legacy_row(f"pelican deploy key {LEGACY_SECRET} end")
    kw = dict(client=client_of(token))
    s = tools.search_context(token, ["pelican"], **kw)
    t = tools.get_timeline(token, "2026-05-01", "2026-05-01", **kw)
    e = tools.get_evidence(token, s["results"][0]["evidence_id"], **kw)
    for resp in (s, t, e):
        assert resp["status"] in ("ok", "source_unavailable")  # synthetic evidence file does not exist
        assert LEGACY_SECRET not in json.dumps(resp)
    assert "[REDACTED]" in s["results"][0]["snippet"]
    assert "[REDACTED]" in e["evidence"]["excerpt"]


def test_query_time_redaction_fails_closed(db, monkeypatch) -> None:
    from mcp_helpers import client_of
    token, _, _ = _legacy_row(f"pelican deploy key {LEGACY_SECRET} end")
    kw = dict(client=client_of(token))
    ok = tools.search_context(token, ["pelican"], **kw)
    eid = ok["results"][0]["evidence_id"]

    def boom(_text):
        raise RuntimeError("detector crashed")

    monkeypatch.setattr(tools, "redact_secrets", boom)
    calls = [tools.search_context(token, ["pelican"], **kw),
             tools.get_timeline(token, "2026-05-01", "2026-05-01", **kw),
             tools.get_evidence(token, eid, **kw)]
    denied = tools.permission_denied()
    for resp in calls:
        assert resp == tools.redaction_failed()
        assert set(resp) == set(denied)  # same uniform shape as denial bodies
        assert "pelican" not in json.dumps(resp) and LEGACY_SECRET not in json.dumps(resp)


