# ── Claude Code fixtures ─────────────────────────────────────────────────────────────────────
def _c(kind: str, n: int, content, session: str = "s1") -> dict:
    return {"type": kind, "uuid": f"u{n}", "sessionId": session, "timestamp": f"2026-05-01T10:{n:02d}:00Z",
            "message": {"role": kind, "content": content}}


def _text(t: str) -> list:
    return [{"type": "text", "text": t}]


def _tool_use(name: str) -> list:
    return [{"type": "tool_use", "id": "toolu_1", "name": name, "input": {"keywords": ["pelican"]}}]


def _tool_result() -> list:
    return [{"type": "tool_result", "tool_use_id": "toolu_1", "content": "[{\"snippet\": \"pelican plan\"}]"}]


def _write(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")


def _claude_events(tmp_path: Path, rows: list[dict], **kw):
    root = tmp_path / "projects"
    _write(root / "-tmp-demo" / "s1.jsonl", rows)
    src = ClaudeCodeSource(projects_root=root, self_exclude_dirs=set(), **kw)
    inst = src.discover()[0]
    return list(src.read(inst, EPOCH, FAR))


